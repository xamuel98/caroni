// Regenerates src/authorization/catalogue.generated.ts from docs/authz.
// Run with: pnpm --filter @caroni/api gen:catalogue  (builds first, then runs this)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { compileCatalogue } = require('../dist/authorization/catalogue.js');

const here = dirname(fileURLToPath(import.meta.url));
const docsDir = resolve(here, '../../../docs/authz');
const csv = readFileSync(resolve(docsDir, 'permission-glossary.csv'), 'utf8');
const yaml = readFileSync(resolve(docsDir, 'roles.yaml'), 'utf8');

const { abilities, roleGrants } = compileCatalogue(csv, yaml);

const output = `// AUTO-GENERATED by scripts/generate-catalogue.mjs — do not edit by hand.
// Source: docs/authz/permission-glossary.csv + docs/authz/roles.yaml
import type { Ability } from '@caroni/shared-types';

export const CATALOGUE: Ability[] = ${JSON.stringify(abilities, null, 2)};

export const ROLE_GRANTS: Record<string, string[]> = ${JSON.stringify(roleGrants, null, 2)};
`;

const outPath = resolve(here, '../src/authorization/catalogue.generated.ts');
writeFileSync(outPath, output);
console.log(
  `wrote ${outPath}: ${abilities.length} abilities, ${Object.keys(roleGrants).length} roles`,
);
